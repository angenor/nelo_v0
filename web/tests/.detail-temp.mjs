import { chromium } from '@playwright/test'
const navigateur = await chromium.launch({ channel: 'chromium' })
const contexte = await navigateur.newContext({ serviceWorkers: 'block', viewport: { width: 1280, height: 720 } })
const page = await contexte.newPage()
const cdp = await contexte.newCDPSession(page)
await cdp.send('Network.enable'); await cdp.send('Network.setCacheDisabled', { cacheDisabled: true })
const urls = new Map(); const tailles = []
cdp.on('Network.requestWillBeSent', (e) => urls.set(e.requestId, e.request.url))
cdp.on('Network.responseReceived', (e) => urls.set(e.requestId, e.response.url + ' [' + (e.response.headers['content-encoding'] ?? e.response.headers['Content-Encoding'] ?? '-') + ']'))
cdp.on('Network.loadingFinished', (e) => tailles.push([e.encodedDataLength, urls.get(e.requestId)]))
await page.goto(process.argv[2], { waitUntil: 'networkidle' })
tailles.sort((a, b) => b[0] - a[0])
for (const [t, u] of tailles) console.log(String(t).padStart(7), u.replace('http://localhost:4310', ''))
console.log('total', tailles.reduce((s, [t]) => s + t, 0))
await navigateur.close()
